#!/bin/bash

#SBATCH --job-name=combgvcf
#SBATCH --time=7-12:00:00
#SBATCH --mem=100G
#SBATCH --cpus-per-task=1

### Description ###

# This script takes multiple GVCF files and outputs a combined GVCF file.
# The code is based on the best Best Practices Workflows from GATK

### Input variables ###

if [ $# -ne 6 ]
then
    echo "Usage: $0 <GVCF files folder> <cohort> <Genome FASTA file> <output prefix>"
    echo ""
    echo "1) folder containing all the GVCF files as generated by find_variants.sh that need to be genotyped together"
    echo "2) cohort name"
    echo "3) reference genome FASTA file, unzipped"
    echo "4) output path"
    exit
fi

chromosome=$1
GVCFspath=$2
dbsnp=$3
cohort_name=$4
reference=$5
# for reference use /exports/ana-scarlab/group_references/ensembl/human/102/Homo_sapiens.GRCh38.dna.primary_assembly_ERCC.fa
outpath=$6
outpath=${outpath%/}

### Paths to utilities and scripts ###

GVCFspath=${GVCFspath%/}
outpath=${outpath%/}
p2gatk=$(which gatk)
p2java=$(which java)

### Code ###

mkdir -p $outpath

# check java version, needs to be JDK version 8 to work with GATK 4.1.9.0

v="$(${p2java} -version 2>&1)"
version=$(echo ${v} | awk -F "." '/version/ {print $2}')
if [ ${version} -ne "8" ]
then
    echo "Java JDK needs to be version 8"
    exit
fi

gvcfs=$(for gvcf in $(ls ${GVCFspath}/*g.vcf.gz); do echo --variant $gvcf; done)

# merge GVCF files
${p2gatk} CombineGVCFs \
    -R $reference $gvcfs  \
    --intervals $chromosome \
    -O ${outpath}/${chromosome}.${cohort_name}.g.vcf.gz

# index cohort GVCF file
${p2gatk} IndexFeatureFile \
    --input ${outpath}/${chromosome}.${cohort_name}.g.vcf.gz \

# genotype GVCF files
${p2gatk} --java-options "-Xmx80g" GenotypeGVCFs \
    --reference $reference \
    --dbsnp $dbsnp \
    --intervals $chromosome \
    --variant ${outpath}/${chromosome}.${cohort_name}.g.vcf.gz \
    --output ${outpath}/${chromosome}.${cohort_name}.vcf.gz

exit
