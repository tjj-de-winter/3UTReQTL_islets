#!/bin/bash

### Description ###

# script to filter VCF files by a minimum minor alle frequency

### Input variables ###
if [ $# -ne 5 ]
then
    echo "Usage: $0 <MAF TSV file> <MAF> <VCF file> <outprefix> <output path>"
    echo "  1) TSV.gz file containing MAFs extracted from 1000 genomes as generated by get_MAF.py"
    echo "  2) MAF threshold as generated by MAF_filter_finder.py, e.g. 0.05"
    echo "  3) feature file (.vcf/.vcf.gz)"
    echo "  4) outprefix"
    echo "  5) output path"
    exit 1
fi

TSVin=$1
MAF=$2
VCFin=$3
outprefix=$4
outdir=$5

outdir=${outdir%/}
VCFout=${outdir}/${outprefix}_MAF${MAF}.vcf.gz
positions=${TSVin}.tmp.txt

### Paths to utilities ###
p2bedtools=$(which bedtools)

### Code ###

mkdir -p ${outdir}

# Make a file containing genomic position of SNPs passing the MAF trheshold
zcat $TSVin |
	awk -v MAF_filter=$MAF '{OFS="\t"}{if ($5 >= MAF_filter) print $1, $2}' |
	sed 's/chr//' > $positions

# Filter VCF file
${p2bedtools} view -R $positions $VCFin -Oz -o $VCFout

rm $positions

exit