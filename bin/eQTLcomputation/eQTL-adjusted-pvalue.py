### Description ###

# Code to perform p-value adjustment using the Benjamini-Hockberg FDR procedure
# optional filtering based on gene expression levels

### Import packages ###
import sys, os
import os.path
import math
import pandas as pd
from statsmodels.stats import multitest
import argparse as argp

### Input variables ###
parser = argp.ArgumentParser(description = 'calculation of Benjamini-Hockberg FDR p-values')
parser.add_argument('--cell_group', help = 'Cell type and group of the eQTL sample')
parser.add_argument('--eqtl', help = 'CSV file with eQTLs, as generated by eQTL_computation.py')
parser.add_argument('--filter_file', help = 'gene filtering CSV file, as generated by generate_gene_filter')
parser.add_argument('--filter', help = 'filter based on gene expression', action='store_true')

args = parser.parse_args()

cell_group = args.cell_group
eqtl = args.eqtl
filter_file = args.filter_file
Filter = args.filter

### Parameters ###
alpha = 0.05 # significance threshold

### Functions ###

def none_or_nan(p):
    '''Add a non significant numerical value (i.e. 1) to non computed variants'''
    if math.isnan(float(p)):
        p = 1
    return p

def matrix_to_txt(df, text_file):
    '''generate a txt file that is used for filtering with grep (bash)'''
    f = open(text_file, "w")
    for idx in df.index:
        for col in df.columns:
            filter = df.loc[idx, col]
            if filter == "PASS" :
                f.write(f"_{idx}_.*{col}\n")

    f.close()

def monotonicity_filter(df):
    index = []
    for i, idx in enumerate(df.index):
        m0 = float(df.iloc[i, list(df.columns).index('med0_cell')])
        m1 = float(df.iloc[i, list(df.columns).index('med1_cell')])
        m2 = float(df.iloc[i, list(df.columns).index('med2_cell')])

        b = float(df.iloc[i, list(df.columns).index('Beta')])

        if m0>m1>m2 and b < 0:
            index.append(i)
        elif m0<m1<m2 and b > 0:
            index.append(i)

    return df.iloc[index,:]

### Code ###

df = pd.read_csv(eqtl)

# add cell_group column
df['Cell_group'] = [cell_group for _ in range(df.shape[0])]

# replace None and nan values as 1
df['pvalue_nan'] = df['pvalue'].apply(lambda p:  none_or_nan(p))
df['pvalue_nan'] = df['pvalue_nan'].astype(float)

# calculate FDR adjusted p-values based per gene
print("start p-value correction")

rejected, pvals_adjusted = multitest.fdrcorrection(list(df['pvalue_nan']), alpha=alpha, method='indep', is_sorted=False)


df['adj_pvalue'] = pvals_adjusted

dfn = df.loc[:,['Gene', 'Variant', 'adj_pvalue', 'Beta', 'Cell_group', 'med0_cell',
       'med1_cell', 'med2_cell']]

outfile = eqtl.replace('.csv', '.unfiltered.adjusted-pvalue.csv')
dfn.to_csv(outfile, index=False)

print(outfile)

# filtering based on general gene expression

if Filter:
    df_filter_matrix = pd.read_csv(filter_file,index_col=0)

    df_filter_matrix.columns = [c.replace('/','-') for c in df_filter_matrix.columns]# fix issue with / sign

    df_filter = df_filter_matrix.loc[:,[cell_group]]

    df_filter = df_filter[df_filter[cell_group] == 'PASS']

    genes = list(df_filter.index)

    dfn = dfn[dfn['Gene'].isin(genes)]

    dfn = monotonicity_filter(dfn)

    outfile_filtered = eqtl.replace('.csv', '.adjusted-pvalue.csv')

    dfn.to_csv(outfile_filtered, index=False)

    print(outfile_filtered)

sys.exit()